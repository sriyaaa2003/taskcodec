"""Generate figures and README.md from results/*.json. Every number comes from the JSONs.

`python -m taskcodec.report` writes README.md; `python -m taskcodec.report --check` regenerates
it in memory and fails if the file on disk differs (README numbers == results/ values).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POLICIES = ["uniform", "variance", "task_kws", "task_sid", "random"]


def _load(rd: Path) -> dict:
    out = {}
    for n in ("tasks", "e1", "e2", "e3", "e4", "ablation", "ae_training"):
        p = rd / f"{n}.json"
        if not p.exists():
            raise FileNotFoundError(f"missing result file {p}; refusing to write a README")
        out[n] = json.load(open(p, encoding="utf-8"))
    return out


def pct(r, k="mean"):
    return f"{100 * r[k]:.1f}"


def cell(r):
    return f"{100 * r['mean']:.1f} [{100 * r['lo']:.1f}, {100 * r['hi']:.1f}]"


def pp(d):
    return f"{100 * d['diff']:+.1f} pp [{100 * d['lo']:+.1f}, {100 * d['hi']:+.1f}]"


def sig(d):
    return "better" if d["lo"] > 0 else ("worse" if d["hi"] < 0 else "no clear difference")


def table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---" for _ in header) + "|\n"
    return s + "\n".join("| " + " | ".join(str(c) for c in r) + " |" for r in rows) + "\n"


def make_figures(R: dict, fig_dir: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig_dir.mkdir(parents=True, exist_ok=True)
    e1 = R["e1"]["rows"]
    fig, axs = plt.subplots(1, 2, figsize=(9, 3.4))
    for ax, task in zip(axs, ("kws", "sid")):
        for pol in POLICIES:
            rs = sorted([r for r in e1 if r["task"] == task and r["policy"] == pol], key=lambda r: r["bpe"])
            ax.errorbar([r["kbps"] for r in rs], [100 * r["mean"] for r in rs],
                        yerr=[[100 * (r["mean"] - r["lo"]) for r in rs], [100 * (r["hi"] - r["mean"]) for r in rs]],
                        marker="o", ms=3, capsize=2, label=pol, alpha=0.8)
        ref = next(r for r in e1 if r["task"] == task and r["policy"] == "autoencoder_unquantized")
        ax.axhline(100 * ref["mean"], ls="--", c="gray", lw=1, label="AE, no quantization")
        ax.set_title(f"E1 {task.upper()} accuracy, clean channel")
        ax.set_xlabel("rate (kbit/s)")
        ax.set_ylabel("accuracy (%)")
    axs[0].legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(fig_dir / "e1_rate_accuracy.png", dpi=130)
    plt.close(fig)

    e2 = R["e2"]["rows"]
    fig, axs = plt.subplots(2, 2, figsize=(9, 6), sharey="row")
    for i, task in enumerate(("kws", "sid")):
        for j, model in enumerate(("iid", "ge")):
            ax = axs[i][j]
            for pol, sch in [(f"task_{task}", "none"), (f"task_{task}", "eep"), (f"task_{task}", "uep_task"),
                             (f"task_{task}", "uep_random")]:
                rs = sorted([r for r in e2 if r["task"] == task and r["policy"] == pol and r["scheme"] == sch
                             and r["loss_model"] == model], key=lambda r: r["p"])
                ax.errorbar([r["p"] for r in rs], [100 * r["mean"] for r in rs],
                            yerr=[[100 * (r["mean"] - r["lo"]) for r in rs], [100 * (r["hi"] - r["mean"]) for r in rs]],
                            marker="o", ms=3, capsize=2, label=sch)
            ax.set_title(f"E2 {task.upper()}, {model} loss")
            ax.set_xlabel("packet loss rate")
            ax.set_ylabel("accuracy (%)")
    axs[0][0].legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(fig_dir / "e2_loss_robustness.png", dpi=130)
    plt.close(fig)


def plan_stats(e1) -> tuple[int, int]:
    """(# task-aware/variance plans that differ from uniform, # plans)."""
    n = d = 0
    for r in e1["rows"]:
        if r.get("policy") in ("variance", "task_kws", "task_sid"):
            for pl in r["plans"]:
                n += len(set(pl["bits"])) > 1
                d += 1
    return n, d


def build_readme(R: dict) -> str:
    t, e1, e2, e3, e4, ab = R["tasks"], R["e1"], R["e2"], R["e3"], R["e4"], R["ablation"]
    cnt = e1["dataset_counts"]
    E = {(r["task"], r["policy"], r.get("bpe")): r for r in e1["rows"]}
    n_diff, n_plans = plan_stats(e1)
    bpes = sorted({r["bpe"] for r in e1["rows"] if r.get("bpe") is not None})
    L: list[str] = []
    L.append("# TaskCodec: task-aware bit allocation and loss protection for a learned speech codec\n")
    L.append("*This README is generated by `python -m taskcodec.report` from `results/*.json`; "
             "every number below is read from those files. Run `python -m taskcodec.report --check` to verify.*\n")
    L.append("## Question\n\nWhen the bit budget is fixed and the channel drops packets, does spending bits and error "
             "protection according to the downstream task (keyword spotting, speaker ID) beat spending them "
             "uniformly or by reconstruction variance?\n")
    L.append("## What was built\n\n"
             "- A small CNN autoencoder on 40-bin log-mel (360k parameters) whose latent is split into G groups; "
             "a per-group scalar quantizer with a fixed bit budget; training with random per-group bit depth, "
             "random packet loss, an extra loss that keeps the decoded features close to what the two frozen task "
             f"models see (their embeddings, weight {e1['config']['ae']['task_weight']}), and, for "
             f"{100 * e1['config']['ae']['aug']['p_nested']:.0f}% of training clips, only the first k groups kept "
             "(ordered latent).\n"
             "- Allocation policies: `uniform`, `variance` (reverse water-filling), `task_kws` / `task_sid` "
             "(gradient sensitivity of the task loss, measured on validation data only), and a `random` control.\n"
             "- A packet-loss channel (i.i.d. and Gilbert-Elliott bursts) with three protection schemes at **equal total "
             "bitrate**: none, equal error protection (EEP, every group sent twice) and unequal error protection "
             "(UEP, only the top-sensitivity groups sent twice; `uep_random` protects random groups as a control).\n"
             "- Two tasks on Google Speech Commands v2: 35-word keyword spotting and closed-set speaker ID over the "
             f"{cnt['n_speakers']} speakers with the most clips. Task models are trained on clean features and frozen.\n")
    L.append(f"Data: {t['n_clips']} clips; KWS train/val/test = {t['kws_counts']['train']}/{t['kws_counts']['val']}/"
             f"{t['kws_counts']['test']}; SID train/val/test = {t['sid_counts']['train']}/{t['sid_counts']['val']}/"
             f"{t['sid_counts']['test']}. Autoencoder training clips: {cnt['ae_train']} (official train, SID val/test "
             "clips excluded). Test data is used only in the experiment runner. Dataset: Google Speech Commands v2 "
             "by Pete Warden, licensed CC BY 4.0 ([paper](https://arxiv.org/abs/1804.03209)).\n")
    L.append(f"Frozen task models on original features: KWS test accuracy {100 * t['kws_test_acc']:.1f}%, "
             f"SID test accuracy {100 * t['sid_test_acc']:.1f}%.\n")

    # ---- findings (rule-generated)
    L.append("## Findings\n")
    F: list[str] = []
    ints = [b for b in bpes if abs(b - round(b)) < 1e-9]
    fracs = [b for b in bpes if b not in ints]
    same = {t: all(E[(t, f"task_{t}", b)]["plans"] == E[(t, "uniform", b)]["plans"] for b in ints) for t in ("kws", "sid")}
    var_diff = [b for b in ints if E[("kws", "variance", b)]["plans"] != E[("kws", "uniform", b)]["plans"]]
    sens = e1.get("sensitivities") or []
    ratios = [max(sc[k]) / min(sc[k]) for sc in sens for k in ("task_kws", "task_sid") if sc.get(k)]
    vr = [max(sc["variance"]) / min(sc["variance"]) for sc in sens if sc.get("variance")]
    rt = f"{min(ratios):.1f}-{max(ratios):.1f}" if ratios else "n/a"
    vt = f"{min(vr):.1f}-{max(vr):.1f}" if vr else "n/a"
    if all(same.values()):
        F.append("**Task-aware allocation reproduced the uniform allocation at whole-number budgets.** "
                 f"At {ints} bit/element the `task_kws` and `task_sid` plans are identical to `uniform`, so their "
                 f"accuracy is identical. The measured task sensitivities are nearly flat (largest over smallest group: "
                 f"{rt}x across autoencoder seeds), so the greedy rule keeps the allocation even; the only differences are "
                 f"at the fractional budgets {fracs}, where leftover bits go to different groups. This is a null result "
                 "for task-aware allocation in this design, not evidence that it cannot help.")
    else:
        F.append("**Task-aware allocation differs from uniform in some whole-number-budget plans.** See the E1 tables.")
    if var_diff:
        F.append(f"**The ordered latent made reconstruction variance informative.** The group variances now differ "
                 f"({vt}x largest over smallest), so `variance` gives non-uniform plans at {var_diff} bit/element and "
                 "changes accuracy there (see tables); the task-based policies did not move.")
    for task in ("kws", "sid"):
        parts = []
        for bb in bpes:
            u, v, r_ = E[(task, "uniform", bb)], E[(task, "variance", bb)], E[(task, "random", bb)]
            parts.append(f"{bb} bit/el: uniform {pct(u)}, variance {pct(v)}, random {pct(r_)}")
        F.append(f"{task.upper()} accuracy % by policy: " + "; ".join(parts) + ".")
    for task in ("kws", "sid"):
        d = [p for p in e1["paired"] if p["task"] == task and p["a"] == f"task_{task}" and p["b"] in ("variance", "random")]
        txt = "; ".join(f"{p['b']} at {p['bpe']} bit/el {pp(p)}" for p in d)
        F.append(f"Paired differences, task-based policy minus other policy on {task.upper()}: {txt}. "
                 "Negative values mean the other policy scored higher.")
    kws_u = E[("kws", "uniform", 2.0)]
    ref_k = E[("kws", "autoencoder_unquantized", None)]
    ref_s = E[("sid", "autoencoder_unquantized", None)]
    F.append(f"**Speaker ID is badly hurt by the mel-latent codec itself.** SID accuracy is {pct(E[('sid', 'original_features', None)])}% "
             f"on original features and {pct(ref_s)}% after the autoencoder with no quantization; KWS drops from "
             f"{pct(E[('kws', 'original_features', None)])}% to {pct(ref_k)}%. Quantizing at 2 bit/element gives KWS "
             f"{pct(kws_u)}% and SID {pct(E[('sid', 'uniform', 2.0)])}%.")
    # E2
    def e2row(task, pol, sch, model, p):
        return next(r for r in e2["rows"] if r["task"] == task and r["policy"] == pol and r["scheme"] == sch
                    and r["loss_model"] == model and r["p"] == p)
    pm = [p for p in sorted({r["p"] for r in e2["rows"]}) if p > 0]
    p_mid = pm[len(pm) // 2 - 1] if len(pm) > 1 else pm[0]
    for task in ("kws", "sid"):
        pr = {p["b"]: p for p in e2["paired"] if p["task"] == task and p["loss_model"] == "iid" and p["p"] == p_mid
              and p["a"] == "task_aware+uep_task"}
        none, eep, rnd = pr[f"task_{task}+none"], pr[f"task_{task}+eep"], pr[f"task_{task}+uep_random"]
        F.append(f"**Protection helps under loss ({task.upper()}, i.i.d. loss {int(p_mid * 100)}%, equal total bitrate).** "
                 f"UEP vs no protection: {pp(none)}; UEP vs EEP: {pp(eep)}; task-selected UEP vs randomly selected UEP: "
                 f"{pp(rnd)} ({sig(rnd)}). The benefit comes from repeating some groups, not from choosing them by task "
                 "sensitivity.")
    chk = all(c["pass"] for c in e2["equal_bitrate_check"])
    F.append(f"Equal-bitrate check across schemes in E2: {'passed' if chk else 'FAILED'} "
             f"(max slack {max(c['max_slack_bits'] for c in e2['equal_bitrate_check'])} bits of "
             f"{e2['equal_bitrate_check'][0]['budget_bits']}).")
    L.append("\n".join(f"- {f}" for f in F) + "\n")

    # ---- E1
    L.append("## E1: rate-accuracy on a clean channel\n\nAccuracy % [95% bootstrap CI over test clips], mean over "
             f"{len(e1['seeds'])} autoencoder seeds. Rates in kbit/s for a 1 s clip.\n")
    for task in ("kws", "sid"):
        rows = []
        for pol in POLICIES:
            rows.append([pol] + [cell(E[(task, pol, b)]) for b in bpes])
        L.append(f"**{task.upper()}**\n\n" + table(["policy"] + [f"{b} bit/el ({E[(task, 'uniform', b)]['kbps']:.2f} kbps)" for b in bpes], rows))
    L.append("![E1](results/figures/e1_rate_accuracy.png)\n")

    # ---- E2
    L.append(f"## E2: robustness to packet loss (total channel budget {e2['rows'][0]['budget_bits']} bits per clip)\n\n"
             "Accuracy % [95% CI]; 'retained' is accuracy divided by the same scheme's accuracy at 0% loss. "
             "Source bits show how many bits remain for the signal after repetitions.\n")
    for task in ("kws", "sid"):
        for model in ("iid", "ge"):
            rows = []
            for pol, sch in [(f"task_{task}", "none"), (f"task_{task}", "eep"), (f"task_{task}", "uep_task"),
                             (f"task_{task}", "uep_random"), ("variance", "none"), ("variance", "eep"), ("uniform", "none")]:
                rr = [e2row(task, pol, sch, model, p) for p in sorted({r["p"] for r in e2["rows"]})]
                rows.append([f"{pol} + {sch}", rr[0]["source_bits"]] + [cell(r) + f" ({100 * r['retained']:.0f}%)" for r in rr])
            ps = sorted({r["p"] for r in e2["rows"]})
            L.append(f"**{task.upper()}, {model} loss**\n\n" + table(["policy + scheme", "source bits"] + [f"p={p}" for p in ps], rows))
    L.append("![E2](results/figures/e2_loss_robustness.png)\n")

    # ---- E3
    L.append("## E3: task specificity\n\nAllocation tuned for task A, evaluated on task B (accuracy % [CI]).\n")
    rows = []
    for b in sorted({r["bpe"] for r in e3["rows"]}):
        for tuned in ("kws", "sid", "variance", "uniform"):
            ev = {r["evaluated_on"]: r for r in e3["rows"] if r["bpe"] == b and r["tuned_for"] == tuned}
            rows.append([b, tuned, cell(ev["kws"]), cell(ev["sid"])])
    L.append(table(["bit/element", "allocation tuned for", "eval KWS", "eval SID"], rows))
    for p in e3["paired"]:
        L.append(f"- {p['bpe']} bit/el, evaluated on {p['evaluated_on'].upper()}: tuned for it vs tuned for the other task: {pp(p)}.")
    L.append("")

    # ---- E4
    c = e4["complexity"]
    L.append("## E4: reconstruction quality and cost\n\nMel L1 is mean absolute error in natural-log mel units over all KWS test clips (lower is better).\n")
    rows = [[r["policy"], r["bpe"], f"{r['kbps']:.2f}", f"{r['mel_l1']['mean']:.3f} [{r['mel_l1']['lo']:.3f}, {r['mel_l1']['hi']:.3f}]"]
            + ([f"{r['stoi']['mean']:.3f} [{r['stoi']['lo']:.3f}, {r['stoi']['hi']:.3f}]"] if "stoi" in r else ["not computed"])
            for r in e4["rows"]]
    L.append(table(["policy", "bit/el", "kbps", "mel L1", "STOI (Griffin-Lim, subset)"], rows))
    L.append(f"STOI note: {e4['stoi_note']}.\n")
    L.append(table(["component", "parameters", "MACs per 1 s clip"],
                   [["encoder", c["encoder_params"], c["encoder_macs"]], ["decoder", c["decoder_params"], c["decoder_macs"]],
                    ["KWS model", c["kws_params"], c["kws_macs"]], ["SID model", c["sid_params"], c["sid_macs"]]]))

    # ---- ablation
    L.append("## Ablation: number of groups G\n\nAccuracy % [CI], one autoencoder seed per G.\n")
    rows = []
    for task in ("kws", "sid"):
        for G in sorted({r["G"] for r in ab["rows"]}):
            for b in sorted({r["bpe"] for r in ab["rows"]}):
                rs = {r["policy"]: r for r in ab["rows"] if r["G"] == G and r["task"] == task and r["bpe"] == b}
                rows.append([task, G, b] + [cell(rs[p]) for p in POLICIES])
    L.append(table(["task", "G", "bit/el"] + POLICIES, rows))
    L.append("Paired differences, task-based policy minus random allocation:\n")
    for p in ab["paired"]:
        if p["b"] == "random":
            L.append(f"- {p['task'].upper()}, G={p['G']}, {p['bpe']} bit/el: {pp(p)}")
    L.append("")

    # ---- limits
    L.append("## Limits and honest caveats\n\n"
             "- One dataset (Speech Commands v2, 1 s clips), two small tasks, one codec family.\n"
             "- The codec is scalar quantization of a mel-spectrogram latent, not a waveform codec; no entropy coding, so "
             "rates are fixed-length bits and packet headers are not counted.\n"
             "- Task models are frozen and trained on clean features; they are not robust to codec artifacts, "
             "which is why accuracy drops even without quantization. Speaker ID drops the most.\n"
             "- The autoencoder is trained to keep what the two task models see, and the same two models score its "
             "output. The task accuracies show how well this codec serves these two models, not how good the audio is "
             "in general.\n"
             "- The ordered latent made the group variances differ, but the task sensitivities stayed nearly equal, so "
             "at whole-number budgets the task-based policies chose the same allocation as uniform (see Findings).\n"
             "- An earlier design (no task-model loss, no ordered latent, 30 instead of 20 training epochs) was run "
             "first on the same test sets; its results are in `results/v1_exchangeable/`. The design reported here "
             "was run after it, so these test sets are not untouched.\n"
             "- Protection is simple repetition, not forward error correction; the equal-rate check allows a slack "
             "of less than two group quanta, and the reported slack is in the E2 file.\n"
             f"- {e4['stoi_note']}.\n"
             "- Bootstrap CIs resample test clips (and are over the seed-averaged per-clip score); they do not capture "
             "variation in task-model training, which used a single seed.\n"
             "- E2 channel realisations: the number of independent draws per clip is in the config; CIs include that averaging.\n")
    L.append("## Reproduce\n\n```\npython -m pytest                      # CPU tests, no dataset\n"
             "python kaggle/sync_code.py            # then push kaggle/code_dataset and the three kernels in kaggle/\n"
             "python -m taskcodec.report            # figures + README from results/*.json\n```\n\n"
             "Kernels run in order: `prep_kernel` (download, features, task models), `train_ae_kernel`, `run_kernel` "
             "(E1-E4, ablation). Configs are in `configs/`; the experiment result files (E1-E4 and the ablation) store "
             "their config hash and seeds. Their git commit field is empty, because the runs used an uploaded copy of "
             "the code before any commit.\n")
    return "\n".join(L)


def d_str(a, b):
    return f"{a} of {b}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--results", default=str(ROOT / "results"))
    a = ap.parse_args()
    rd = Path(a.results)
    R = _load(rd)
    text = build_readme(R)
    out = ROOT / "README.md"
    if a.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print("README.md does not match results/")
            sys.exit(1)
        print("README.md matches results/")
        return
    make_figures(R, rd / "figures")
    out.write_text(text, encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
